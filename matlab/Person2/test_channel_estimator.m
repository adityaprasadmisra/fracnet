%% Local test helper
function run_fixed_channel_test(label, channel, Xpilot, cfg, A, ...
    atomNorms, pairCache, dopplerGrid, delayGrid)

    fprintf('\n--- %s ---\n', label);

    tx = modulate_training_sequence(Xpilot,cfg);
    rx = apply_fractional_doppler_channel(tx,channel,cfg);
    Yclean = demodulate_training_sequence(rx,cfg);

    [Hest, estimatedPaths, estimatedGains, residual, info] = ...
        fractional_doppler_coarse_estimation( ...
        Yclean, A, dopplerGrid, delayGrid, cfg, atomNorms, pairCache);

    fprintf('True [Doppler, Delay]:\n');
    disp([channel.doppler(:), channel.delay(:)]);
    fprintf('Estimated [Doppler, Delay]:\n');
    disp(estimatedPaths);

    fprintf('True physical gains:\n');
    disp(channel.gain(:));
    fprintf('Estimated physical gains (path order may differ):\n');
    disp(estimatedGains);

    responseNMSE = norm(Hest(:)-Yclean(:))^2 / ...
        (norm(Yclean(:))^2 + eps);
    fprintf('Response reconstruction NMSE = %.6e (%.2f dB)\n', ...
        responseNMSE, 10*log10(responseNMSE+eps));
    fprintf('Estimator residual NMSE       = %.6e\n', info.fit_nmse);
    fprintf('Selected atom coherence       = %.8f\n', ...
        info.selected_atom_coherence);
    fprintf('Selected pair Gram condition  = %.3e\n', ...
        info.selected_pair_gram_condition);
    fprintf('Ambiguous / near-degenerate  = %d / %d\n', ...
        info.multi_hypothesis_ambiguous,info.near_degenerate_pair_flag);
    fprintf('Alternative delta log-likelihood = %.4g\n', ...
        info.ambiguity_delta_log_likelihood);
    fprintf('Effective pair-condition limit = %.3e\n', ...
        info.max_pair_condition_used);
    fprintf('Close-pair seeds / residual seeds / total = %d / %d / %d\n', ...
        info.close_pair_seed_count,info.residual_seed_count, ...
        info.coarse_seed_count);
    fprintf('Selected refinement source    = %s\n', ...
        info.selected_refinement_source);
    fprintf('LM calls / iterations / steps = %d / %d / %d\n', ...
        info.lm_calls,info.lm_total_iterations,info.lm_total_accepted_steps);
    fprintf('LM retries / Nelder-Mead starts / projected endpoints = %d / %d / %d\n', ...
        info.lm_retry_calls,numel(info.nelder_mead_candidate_indices), ...
        info.nelder_mead_projected_endpoints);

    if responseNMSE > 1e-3
        warning('%s reconstruction NMSE exceeded 1e-3.', label);
    else
        fprintf('PASS: %s noiseless response reconstruction.\n', label);
    end

    if norm(residual(:)) > norm(Yclean(:))
        warning('Estimator residual is larger than the received response.');
    end
end

function verify_revision20_function(functionName,expectedDir,expectedInputs,expectedOutputs)
% VERIFY_REVISION20_FUNCTION
% Check that MATLAB is using the file shipped in this Person 2 package and
% that its public function signature matches the calls in this test driver.
    expectedFile = fullfile(expectedDir,[functionName '.m']);
    actualFile = which(functionName);
    if isempty(actualFile)
        error('Required function %s is not on the MATLAB path.',functionName);
    end
    actualComparable = strrep(actualFile,'/','\');
    expectedComparable = strrep(expectedFile,'/','\');
    if ~strcmpi(actualComparable,expectedComparable)
        error(['Function resolution conflict for %s. MATLAB selected:\n  %s\n', ...
            'but Revision 20 requires:\n  %s\n', ...
            'Remove/rename the duplicate file or run from the Revision 20 Person2 folder.'], ...
            functionName,actualFile,expectedFile);
    end
    try
        actualInputs = nargin(functionName);
        actualOutputs = nargout(functionName);
    catch signatureError
        error(['MATLAB resolved %s to %s, but it is not callable with the ', ...
            'expected function interface. Replace it with the Revision 20 file. ', ...
            'MATLAB message: %s'],functionName,actualFile,signatureError.message);
    end
    if actualInputs ~= expectedInputs || actualOutputs ~= expectedOutputs
        error(['Wrong function signature for %s. Found nargin=%d, nargout=%d; ', ...
            'Revision 20 requires nargin=%d, nargout=%d. File: %s'], ...
            functionName,actualInputs,actualOutputs, ...
            expectedInputs,expectedOutputs,actualFile);
    end
    fprintf('Resolved %-42s nargin=%d, nargout=%d\n', ...
        actualFile,actualInputs,actualOutputs);
end
